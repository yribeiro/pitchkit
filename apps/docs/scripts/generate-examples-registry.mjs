// Generates components/examples/registry.ts from every *-basic.tsx file in
// components/examples/. Invoked both from the npm "generate" script (for
// local dev/lint/typecheck) and synchronously from the top of next.config.ts,
// because Vercel's Next.js framework preset runs `next build` directly
// against this app's Root Directory — bypassing package.json's "build"
// script (and any pre/post npm hooks) entirely. registry.ts is gitignored,
// so without the next.config.ts call it's simply missing in that build path.
//
// Each example file's raw source becomes the "view code" panel's content
// (see components/pitch-preview.tsx), and its default-cased export becomes
// the live-rendered component. Reading the file at build time (rather than
// a bundler `?raw` import or a runtime fs read) keeps this working
// identically under Turbopack and webpack, and keeps every example a
// normal, independently type-checked/lintable .tsx file.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

function toPascalCase(kebabName) {
  return kebabName
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

export function generateExamplesRegistry() {
  const examplesDir = fileURLToPath(new URL("../components/examples", import.meta.url));
  const outputFile = path.join(examplesDir, "registry.ts");

  // `-basic.tsx` = the minimal per-feature docs examples; `-gallery.tsx` = the
  // finished visualisations on /gallery. Same registry, same preview pipeline.
  const exampleFiles = readdirSync(examplesDir)
    .filter((file) => file.endsWith("-basic.tsx") || file.endsWith("-gallery.tsx"))
    .sort();

  const entries = exampleFiles.map((file) => {
    const name = file.replace(/\.tsx$/, "");
    const exportName = toPascalCase(name);
    const source = readFileSync(path.join(examplesDir, file), "utf8").trimEnd();
    return { name, exportName, file, source };
  });

  const imports = entries
    .map((entry) => `import { ${entry.exportName} } from "./${entry.name}";`)
    .join("\n");

  const registryEntries = entries
    .map(
      (entry) =>
        `  "${entry.name}": { Component: ${entry.exportName}, source: ${JSON.stringify(entry.source)} },`,
    )
    .join("\n");

  const output = `// AUTO-GENERATED by scripts/generate-examples-registry.mjs — do not edit by hand.
import type { ComponentType } from "react";
${imports}

export const registry: Record<string, { Component: ComponentType; source: string }> = {
${registryEntries}
};
`;

  writeFileSync(outputFile, output);
  return entries.length;
}

// Allow `node scripts/generate-examples-registry.mjs` to keep working for the
// npm "generate" script, while next.config.ts imports generateExamplesRegistry
// directly instead of shelling out.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const count = generateExamplesRegistry();
  console.log(`Generated registry.ts with ${count} example(s).`);
}
